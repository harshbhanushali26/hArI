-- ==============================================================================
-- hArI v2 Database Schema & Migrations
-- Target: Supabase PostgreSQL (pgvector + full-text search)
-- ==============================================================================

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==============================================================================
-- 2. TABLES
-- ==============================================================================

-- Documents table (PDF chunks & 384-dimensional embeddings)
CREATE TABLE IF NOT EXISTS public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content TEXT NOT NULL,
    metadata JSONB DEFAULT '{}'::jsonb,
    embedding vector(384) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Chat Sessions table (Sidebar conversation history)
CREATE TABLE IF NOT EXISTS public.chat_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Messages table (Turn-by-turn chat persistence)
CREATE TABLE IF NOT EXISTS public.messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES public.chat_sessions(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Telemetry table (User feedback logging)
CREATE TABLE IF NOT EXISTS public.telemetry (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID REFERENCES public.chat_sessions(id) ON DELETE SET NULL,
    query TEXT NOT NULL,
    response TEXT NOT NULL,
    feedback INT CHECK (feedback IN (0, 1)),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 3. PERFORMANCE INDEXES
-- ==============================================================================

CREATE INDEX IF NOT EXISTS idx_documents_user_filename ON public.documents (user_id, filename);
CREATE INDEX IF NOT EXISTS idx_chat_sessions_user ON public.chat_sessions (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_messages_session ON public.messages (session_id, created_at ASC);

-- Full-Text Search index (GIN) on PDF document content
CREATE INDEX IF NOT EXISTS idx_documents_fts ON public.documents USING gin (to_tsvector('english', content));

-- Vector Cosine Similarity index (HNSW) for fast ANN search
CREATE INDEX IF NOT EXISTS idx_documents_embedding ON public.documents USING hnsw (embedding vector_cosine_ops);

-- ==============================================================================
-- 4. ROW-LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================

ALTER TABLE public.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telemetry ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can manage own documents"
    ON public.documents FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can manage own chat sessions"
    ON public.chat_sessions FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can manage own messages"
    ON public.messages FOR ALL
    USING (
        EXISTS (
            SELECT 1 FROM public.chat_sessions
            WHERE chat_sessions.id = messages.session_id
            AND chat_sessions.user_id = auth.uid()
        )
    );

CREATE POLICY "Users can insert telemetry"
    ON public.telemetry FOR INSERT
    WITH CHECK (auth.role() = 'authenticated');

-- ==============================================================================
-- 5. HYBRID SEARCH RPC FUNCTION
-- Combines pgvector cosine similarity with full-text keyword search (ts_rank)
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.hybrid_search (
  query_text text,
  query_embedding vector(384),
  match_count int
)
RETURNS TABLE (
  id bigint,
  content text,
  metadata jsonb,
  similarity float
)
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  rrf_k int := 60; -- Standard RRF smoothing constant
BEGIN
  RETURN QUERY
  WITH semantic_search AS (
    SELECT
      documents.id,
      documents.content,
      documents.metadata,
      ROW_NUMBER() OVER (ORDER BY documents.embedding <=> query_embedding) AS rank
    FROM public.documents
    WHERE documents.user_id = auth.uid()
      AND (1 - (documents.embedding <=> query_embedding)) > 0.3
    LIMIT match_count * 2
  ),
  keyword_search AS (
    SELECT
      documents.id,
      documents.content,
      documents.metadata,
      ROW_NUMBER() OVER (
        ORDER BY ts_rank(to_tsvector('english', documents.content), plainto_tsquery('english', query_text)) DESC
      ) AS rank
    FROM public.documents
    WHERE documents.user_id = auth.uid()
      AND to_tsvector('english', documents.content) @@ plainto_tsquery('english', query_text)
    LIMIT match_count * 2
  )
  SELECT
    COALESCE(s.id, k.id) AS id,
    COALESCE(s.content, k.content) AS content,
    COALESCE(s.metadata, k.metadata) AS metadata,
    -- Reciprocal Rank Fusion Formula: 1 / (60 + rank_semantic) + 1 / (60 + rank_keyword)
    (
      COALESCE(1.0 / (rrf_k + s.rank), 0.0) +
      COALESCE(1.0 / (rrf_k + k.rank), 0.0)
    )::float AS similarity
  FROM semantic_search s
  FULL OUTER JOIN keyword_search k ON s.id = k.id
  ORDER BY similarity DESC
  LIMIT match_count;
END;
$$;